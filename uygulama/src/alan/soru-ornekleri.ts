/** Programla gelen bir sorunun örneği; yazar metni değiştirmişse ya da soru programdan gelmiyorsa null. */
export function soruOrnegi(q: { kod: string; metin: string }): string | null {
  const ornek = SORU_ORNEKLERI[q.kod];
  if (!ornek) return null;
  const asil = soruSetiBul(q.kod.split('.')[0])?.sorular.find((x) => x.kod === q.kod);
  return asil && asil.metin === q.metin ? ornek : null;
}
